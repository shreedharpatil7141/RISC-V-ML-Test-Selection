#!/usr/bin/env python3
"""Generate Stage-1 directed self-checking RV32I tests (tests/directed/rv32i/*.s) + manifest.csv.
Convention: gp(x3)=test number before each check (>=2); pass => gp=1 then ECALL; fail => ECALL with gp!=1.
Expected values come from the Python semantic models below (independent of the RTL and of the ISS)."""
import os, random
M = 0xFFFFFFFF
def s32(x): x &= M; return x - (1 << 32) if x >> 31 else x
def sx12(x): return ((x & 0xFFF) ^ 0x800) - 0x800
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'tests', 'directed', 'rv32i')
CORN = [0, 1, 0xFFFFFFFF, 0x7FFFFFFF, 0x80000000, 0x12345678, 0xA5A5A5A5, 2, 31, 0xFFFFFFFE]
RR = {'add': lambda a,b:(a+b)&M, 'sub': lambda a,b:(a-b)&M, 'sll': lambda a,b:(a<<(b&31))&M,
      'slt': lambda a,b:int(s32(a)<s32(b)), 'sltu': lambda a,b:int(a<b), 'xor': lambda a,b:a^b,
      'srl': lambda a,b:a>>(b&31), 'sra': lambda a,b:(s32(a)>>(b&31))&M, 'or': lambda a,b:a|b, 'and': lambda a,b:a&b}
BR = {'beq': lambda a,b:a==b, 'bne': lambda a,b:a!=b, 'blt': lambda a,b:s32(a)<s32(b),
      'bge': lambda a,b:s32(a)>=s32(b), 'bltu': lambda a,b:a<b, 'bgeu': lambda a,b:a>=b}

class Prog:
    def __init__(s): s.l = []; s.n = 1; s.u = 0
    def add(s, *x): s.l += list(x)
    def t(s): s.n += 1; s.l.append(f"li gp, {s.n}")
    def chk(s, a, b):
        s.u += 1; s.l += [f"beq {a}, {b}, ok{s.u}", "j fail", f"ok{s.u}:"]
    def text(s, name, footer=True):
        body = f"# {name} (generated by gen_rv32i_tests.py - do not edit)\n" + "\n".join(s.l) + "\n"
        if footer: body += "li gp, 1\necall\nfail:\necall\n"
        return body

tests = {}      # name -> (source, expect_cause, check_gp)
def add(name, src, cause=1, gp=1): tests[name] = (src, cause, gp)

# ---- R-type ----
for op, f in RR.items():
    p = Prog()
    for a in CORN:
        for b in CORN:
            p.t(); p.add(f"li t0, {a}", f"li t1, {b}", f"{op} t2, t0, t1", f"li t3, {f(a,b)}"); p.chk('t2', 't3')
    for a, b in [(0x80000000, 31), (0x12345678, 0xA5A5A5A5), (0xFFFFFFFF, 1)]:   # rd aliasing
        p.t(); p.add(f"li t0, {a}", f"li t1, {b}", f"{op} t0, t0, t1", f"li t3, {f(a,b)}"); p.chk('t0', 't3')
        p.t(); p.add(f"li t0, {a}", f"li t1, {b}", f"{op} t1, t0, t1", f"li t3, {f(a,b)}"); p.chk('t1', 't3')
        p.t(); p.add(f"li t0, {a}", f"{op} t0, t0, t0", f"li t3, {f(a,a)}"); p.chk('t0', 't3')
    add(f"rr_{op}", p.text(f"rr_{op}"))

# ---- I-type ALU ----
IMMS = [0, 1, -1, 2047, -2048, 0x555, -0x556, 0x7FF]
IM = {'addi': lambda a,i:(a+i)&M, 'slti': lambda a,i:int(s32(a)<i), 'sltiu': lambda a,i:int(a<(i&M)),
      'xori': lambda a,i:(a^i)&M, 'ori': lambda a,i:(a|i)&M, 'andi': lambda a,i:(a&i)&M}
for op, f in IM.items():
    p = Prog()
    for a in CORN:
        for i in IMMS:
            p.t(); p.add(f"li t0, {a}", f"{op} t2, t0, {i}", f"li t3, {f(a,i)}"); p.chk('t2', 't3')
        p.t(); p.add(f"li t0, {a}", f"{op} t0, t0, 7", f"li t3, {f(a,7)}"); p.chk('t0', 't3')   # rd==rs1
    add(f"imm_{op}", p.text(f"imm_{op}"))
SH = {'slli': lambda a,s:(a<<s)&M, 'srli': lambda a,s:a>>s, 'srai': lambda a,s:(s32(a)>>s)&M}
for op, f in SH.items():
    p = Prog()
    for a in CORN:
        for s in [0, 1, 7, 15, 16, 31]:
            p.t(); p.add(f"li t0, {a}", f"{op} t2, t0, {s}", f"li t3, {f(a,s)}"); p.chk('t2', 't3')
    add(f"imm_{op}", p.text(f"imm_{op}"))

# ---- Upper immediates ----
p = Prog()
for v in [0, 1, 0x12345, 0xFFFFF, 0x80000, 0x7FFFF, 0x00800]:
    p.t(); p.add(f"lui t0, {v}", f"li t3, {(v<<12)&M}"); p.chk('t0', 't3')
add("upper_lui", p.text("upper_lui"))
p = Prog()
for v in [0, 1, 0x12345, 0xFFFFF, 0x80000, 0x7FFFF]:
    p.t(); lab = f"au{p.n}"
    p.add(f"{lab}:", f"auipc t0, {v}", f"la t1, {lab}", f"li t2, {(v<<12)&M}", "add t1, t1, t2"); p.chk('t0', 't1')
add("upper_auipc", p.text("upper_auipc"))

# ---- Branches (forward, taken and not-taken, per op) ----
BC = [0, 1, 0xFFFFFFFF, 0x7FFFFFFF, 0x80000000, 2, 0xA5A5A5A5]
for op, f in BR.items():
    p = Prog()
    for a in BC:
        for b in BC:
            p.t(); k = p.n; p.add(f"li t0, {a}", f"li t1, {b}")
            if f(a, b): p.add(f"{op} t0, t1, bt{k}", "j fail", f"bt{k}:")
            else:       p.add(f"{op} t0, t1, bf{k}", f"j bc{k}", f"bf{k}:", "j fail", f"bc{k}:")
    add(f"branch_{op}", p.text(f"branch_{op}"))

# ---- Backward branches (loops) ----
p = Prog()
p.t(); p.add("li t0, 0", "li t1, 5", "L1:", "addi t0, t0, 1", "bne t0, t1, L1", "li t3, 5"); p.chk('t0', 't3')
p.t(); p.add("li t0, 0", "li t1, 5", "L2:", "addi t0, t0, 1", "blt t0, t1, L2", "li t3, 5"); p.chk('t0', 't3')
p.t(); p.add("li t0, 0", "li t1, 5", "L3:", "addi t0, t0, 1", "bltu t0, t1, L3", "li t3, 5"); p.chk('t0', 't3')
p.t(); p.add("li t0, 5", "L4:", "addi t0, t0, -1", "bge t0, x0, L4", "li t3, -1"); p.chk('t0', 't3')
p.t(); p.add("li t0, 5", "li t1, 1", "L5:", "addi t0, t0, -1", "bgeu t0, t1, L5"); p.chk('t0', 'x0')
p.t(); p.add("li t0, 0", "li t2, 3", "li t5, 1", "L6:", "addi t0, t0, 1", "xor t3, t0, t2", "sltu t4, x0, t3",
             "beq t4, t5, L6", "li t3, 3"); p.chk('t0', 't3')
add("branch_backward", p.text("branch_backward"))

# ---- Jumps ----
p = Prog()
p.t(); p.add("Lj1: jal t0, J1", "j fail", "J1:", "la t1, Lj1", "addi t1, t1, 4"); p.chk('t0', 't1')          # forward JAL link
p.t(); p.add("j JS2", "JT2: j JA2", "JS2: jal t0, JT2", "JR2: j fail", "JA2:", "la t1, JR2"); p.chk('t0', 't1')   # backward JAL
p.t(); p.add("la t1, J3", "Lj3: jalr t0, 0(t1)", "j fail", "J3:", "la t2, Lj3", "addi t2, t2, 4"); p.chk('t0', 't2')
p.t(); p.add("la t1, J4", "addi t1, t1, -8", "Lj4: jalr t0, 8(t1)", "j fail", "J4:", "la t2, Lj4", "addi t2, t2, 4"); p.chk('t0', 't2')
p.t(); p.add("la t1, J5", "addi t1, t1, 1", "jalr x0, 0(t1)", "j fail", "J5:", "li t2, 5", "li t3, 5"); p.chk('t2', 't3')  # bit0 cleared
p.t(); p.add("la t1, J6", "Lj6: jalr t1, 0(t1)", "j fail", "J6:", "la t2, Lj6", "addi t2, t2, 4"); p.chk('t1', 't2')   # rd==rs1
p.t(); p.add("li t0, 77", "jal x0, J7", "j fail", "J7:", "li t3, 77"); p.chk('t0', 't3')                          # rd=x0 untouched
p.t(); p.add("la ra, J8", "jalr x0, 0(ra)", "j fail", "J8:", "li t0, 1", "li t1, 1"); p.chk('t0', 't1')
add("jumps", p.text("jumps"))

# ---- Loads/stores: directed ----
BASE = 0x5000
p = Prog(); p.add(f"li s0, {BASE}")
p.t(); p.add("li t0, 0x80817F01", "sw t0, 0(s0)", "lw t1, 0(s0)", "li t3, 0x80817F01"); p.chk('t1', 't3')
for off, lb, lbu in [(0, 0x01, 0x01), (1, 0x7F, 0x7F), (2, -0x7F, 0x81), (3, -0x80, 0x80)]:
    p.t(); p.add(f"lb t1, {off}(s0)", f"li t3, {lb}"); p.chk('t1', 't3')
    p.t(); p.add(f"lbu t1, {off}(s0)", f"li t3, {lbu}"); p.chk('t1', 't3')
for off, lh_v, lhu in [(0, 0x7F01, 0x7F01), (2, ((0x8081 ^ 0x8000) - 0x8000), 0x8081)]:
    p.t(); p.add(f"lh t1, {off}(s0)", f"li t3, {lh_v}"); p.chk('t1', 't3')
    p.t(); p.add(f"lhu t1, {off}(s0)", f"li t3, {lhu}"); p.chk('t1', 't3')
p.t(); p.add("li t0, -1", "sw t0, 4(s0)", "sb x0, 5(s0)", "lw t1, 4(s0)", "li t3, 0xFFFF00FF"); p.chk('t1', 't3')       # SB byte lane
p.t(); p.add("sh x0, 6(s0)", "lw t1, 4(s0)", "li t3, 0x0000" + "00FF"); p.chk('t1', 't3')                         # SH upper half
p.t(); p.add("li t0, 0xAABBCCDD", "sw t0, 8(s0)", "li t0, 0x11", "sb t0, 8(s0)", "li t0, 0x22", "sb t0, 9(s0)",
             "li t0, 0x33", "sb t0, 10(s0)", "li t0, 0x44", "sb t0, 11(s0)", "lw t1, 8(s0)", "li t3, 0x44332211"); p.chk('t1', 't3')
p.t(); p.add("li t0, 0x12345678", "sh t0, 12(s0)", "li t0, 0x9ABCDEF0", "sh t0, 14(s0)", "lw t1, 12(s0)", "li t3, 0xDEF05678"); p.chk('t1', 't3')
p.t(); p.add(f"li t0, {BASE+0x100}", "li t1, 0xCAFEBABE", "sw t1, -256(t0)", "lw t2, 0(s0)", "li t3, 0xCAFEBABE"); p.chk('t2', 't3')  # negative offset
p.t(); p.add("li t1, 0x13572468", "sw t1, 2044(s0)", "lw t2, 2044(s0)", "li t3, 0x13572468"); p.chk('t2', 't3')
p.t(); p.add("li t1, 0x2468ACE0", "sw t1, -2048(s0)", "lw t2, -2048(s0)", "li t3, 0x2468ACE0"); p.chk('t2', 't3')
p.t(); p.add("li t0, 0xDEADBEEF", "sw t0, 16(s0)", "lw x0, 16(s0)", "li t3, 0"); p.chk('x0', 't3')                    # load to x0
p.t(); p.add("sw x0, 16(s0)", "lw t1, 16(s0)"); p.chk('t1', 'x0')                                                  # store x0
p.t(); p.add("li t0, 0x7788", "sw t0, 20(s0)", "lw s0, 20(s0)", f"li t3, 0x7788"); p.chk('s0', 't3')               # rd==base
add("loadstore_directed", p.text("loadstore_directed"))

# ---- Loads/stores: seeded random vs Python memory model ----
rng = random.Random(20260101)
p = Prog(); p.add(f"li s0, {BASE}")
mem = bytearray(0x10000)
for _ in range(400):
    off = rng.randrange(-32, 32) if rng.random() < 0.7 else rng.randrange(-2048, 2048)
    kind = rng.choice(['sb','sh','sw','lb','lbu','lh','lhu','lw'])
    n = {'b':1,'h':2,'w':4}[kind[1] if kind[0]=='s' else kind[1]]
    off -= off % n
    if off < -2048: off += n
    ad = BASE + off
    p.t()
    if kind[0] == 's':
        v = rng.getrandbits(32)
        p.add(f"li t1, {v}", f"{kind} t1, {off}(s0)")
        mem[ad:ad+n] = (v & ((1 << 8*n) - 1)).to_bytes(n, 'little')
    else:
        raw = int.from_bytes(mem[ad:ad+n], 'little')
        if kind in ('lb', 'lh'): raw = ((raw ^ (1 << (8*n-1))) - (1 << (8*n-1))) & M
        p.add(f"{kind} t2, {off}(s0)", f"li t3, {raw}"); p.chk('t2', 't3')
add("loadstore_random", p.text("loadstore_random"))

# ---- Register file ----
p = Prog()
vals = {r: (0x9E3779B1 * r) & M for r in range(1, 32) if r != 3}
for r, v in vals.items():
    tmp, tmp2 = (28, 29) if r not in (28, 29) else (30, 31)
    p.add(f"li x{r}, {v}", f"add x{tmp}, x{r}, x0", f"li x{tmp2}, {v}", f"beq x{tmp}, x{tmp2}, rp{r}", "j fail", f"rp{r}:",
          f"add x{tmp}, x0, x{r}", f"beq x{tmp}, x{tmp2}, rq{r}", "j fail", f"rq{r}:")
    # re-load clobbered temps with their canonical values
    for c in (tmp, tmp2):
        if c in vals and c < r:  p.add(f"li x{c}, {vals[c]}")
for r, v in vals.items():                                   # all registers still intact?
    p.add(f"li gp, {v}", f"beq x{r}, gp, rv{r}", "j fail", f"rv{r}:")
p.add("li gp, 0x33333333", "li x5, 0x33333333", "beq gp, x5, rg3", "j fail", "rg3:")
add("regfile", p.text("regfile"))

# ---- x0 behaviour ----
p = Prog(); p.add(f"li s0, {BASE}")
p.t(); p.add("addi x0, x0, 5", "lui x0, 0x12345", "auipc x0, 1", "jal x0, X1", "j fail", "X1:", "add x0, x0, x0", "sub x0, x0, x0",
             "li t0, -1", "or x0, t0, t0", "slli x0, t0, 4", "add t1, x0, x0"); p.chk('t1', 'x0')
p.t(); p.add("li t0, 0xDEADBEEF", "sw t0, 0(s0)", "sw x0, 0(s0)", "lw t1, 0(s0)"); p.chk('t1', 'x0')
p.t(); p.add("addi t1, x0, 0", "or t2, x0, x0"); p.chk('t1', 't2')
p.t(); p.add("li t0, 5", "add t1, t0, x0", "li t3, 5"); p.chk('t1', 't3')
add("x0_behavior", p.text("x0_behavior"))

# ---- FENCE as NOP ----
p = Prog()
p.t(); p.add("li t0, 5", "fence", "addi t0, t0, 1", ".word 0x0330000f", ".word 0x0210000f", "li t3, 6"); p.chk('t0', 't3')
add("fence_nop", p.text("fence_nop"))

# ---- Not-taken branch/with misaligned target is NOT an exception ----
p = Prog()
p.t(); p.add("li t0, 1", "bne x0, x0, 6", "li t1, 9", "li t3, 9"); p.chk('t1', 't3')
add("branch_notaken_misaligned_ok", p.text("branch_notaken_misaligned_ok"))

# ---- Long-offset branch / JAL (exercise high immediate bits). Unwritten memory is 0x00000000 = illegal,
# so landing anywhere but the intended target halts with cause 3 => FAIL. ----
def long_test(kind, d):
    """kind 'b' (beq x0,x0) or 'j' (jal x0). d = signed byte offset (multiple of 4)."""
    op = "beq x0, x0," if kind == 'b' else "jal x0,"
    if d > 0:
        tgt = 4 + d
        src = f"li gp, 2\n{op} {d}\nj fail\n.org {tgt}\nli gp, 1\necall\nfail:\necall\n"
    else:
        tgt = 0x40; S = tgt + (-d) - 4
        src = (f"j S\n.org {tgt}\nli gp, 1\necall\nfail:\necall\n.org {S}\nS: li gp, 2\n{op} {d}\nj fail\n")
    return f"# long-offset {kind} d={d} (generated)\n" + src
for d in [1024, 1364, 2048, 2732, 3412, 4092, -1024, -1364, -2048, -2732, -3412, -4092, -4096]:
    add(f"long_beq_{'p' if d > 0 else 'n'}{abs(d)}", long_test('b', d))
for k in range(2, 16):
    add(f"long_jal_p{1 << k}", long_test('j', 1 << k))
for d in [0x5554, 0x2AA8, 0x7FFC, -0x5554, -0x2AA8, -(1 << 15), -(1 << 13), -(1 << 11), -4096, -0x7FFC]:
    add(f"long_jal_{'p' if d > 0 else 'n'}{abs(d)}", long_test('j', d))

# ================= Negative tests (halt-cause expected) =================
def neg(name, body, cause): add(name, "# generated negative test\n" + body + "\n", cause, 0)
neg("halt_ebreak", "li t0, 7\nebreak", 2)
neg("illegal_zero", "li t0, 1\n.word 0x00000000", 3)
neg("illegal_ones", "li t0, 1\n.word 0xFFFFFFFF", 3)
# Reserved funct7 on the OP opcode. funct7=0000001 is the legal RV32M encoding from Stage 3 (this slot used to test
# "M is illegal"). Six approved reserved values; funct3 varied so SUB/SRA/neighbouring funct3 slots are also hit.
for _f7, _f3 in [("0000010", 0), ("0000011", 4), ("0000100", 5), ("0010000", 0), ("1000000", 7), ("0100001", 5)]:
    _w = (int(_f7, 2) << 25) | (2 << 20) | (1 << 15) | (_f3 << 12) | (5 << 7) | 0x33     # rd=x5 rs1=x1 rs2=x2
    neg(f"illegal_op_funct7_{_f7}", f"li t0, 1\n.word 0x{_w:08x}", 3)
neg("illegal_slli_funct7", "li t0, 1\n.word 0x40109093", 3)           # SLLI with funct7=0100000
neg("illegal_srli_funct7", "li t0, 1\n.word 0x20105093", 3)           # SRLI-pattern funct7=0010000
neg("illegal_op_funct7", "li t0, 1\n.word 0x40107033", 3)             # AND with funct7=0100000
neg("illegal_branch_f3_010", "li t0, 1\n.word 0x00002063", 3)
neg("illegal_branch_f3_011", "li t0, 1\n.word 0x00003063", 3)
neg("illegal_load_f3_011", "li t0, 1\n.word 0x00003003", 3)
neg("illegal_load_f3_110", "li t0, 1\n.word 0x00006003", 3)
neg("illegal_store_f3_011", "li t0, 1\n.word 0x00003023", 3)
neg("illegal_jalr_f3_001", "li t0, 1\n.word 0x000010E7", 3)
neg("illegal_csrrw_stage1", "li t0, 1\n.word 0x30551073", 3)          # CSRRW x0,mtvec,a0 : legal from Stage 6
neg("illegal_mret_stage1", "li t0, 1\n.word 0x30200073", 3)           # MRET: legal from Stage 7
neg("illegal_fencei_stage1", "li t0, 1\n.word 0x0000100F", 3)         # FENCE.I: legal from Stage 6
neg("illegal_compressed_stage1", "li t0, 1\n.word 0x00000001", 3)     # low bits != 11 : legal RVC from Stage 4
neg("illegal_opcode_custom", "li t0, 1\n.word 0x0000000B", 3)
neg("misalign_lw_off2", f"li s0, {BASE}\nli t0, 1\nlw t1, 2(s0)", 4)
neg("misalign_lw_off1", f"li s0, {BASE}\nlw t1, 1(s0)", 4)
neg("misalign_lh_off1", f"li s0, {BASE}\nlh t1, 1(s0)", 4)
neg("misalign_lhu_off3", f"li s0, {BASE}\nlhu t1, 3(s0)", 4)
neg("misalign_sw_off1", f"li s0, {BASE}\nli t0, -1\nsw t0, 1(s0)", 5)
neg("misalign_sw_off2", f"li s0, {BASE}\nli t0, -1\nsw t0, 2(s0)", 5)
