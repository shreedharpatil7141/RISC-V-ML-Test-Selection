if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith('.s') or f == 'manifest.csv': os.remove(os.path.join(OUT, f))
    with open(os.path.join(OUT, 'manifest.csv'), 'w') as m:
        m.write("name,expect_cause,check_gp\n")
        for name, (src, cause, gp) in sorted(tests.items()):
            open(os.path.join(OUT, name + '.s'), 'w').write(src)
            m.write(f"{name},{cause},{gp}\n")
    print(f"generated {len(tests)} tests -> {os.path.normpath(OUT)}")
