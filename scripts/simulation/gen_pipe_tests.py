addg("pipe_fwd_wb_bypass", g, stl=True, red=True)

g = G(); g.t(); g.li(5, 1); g.opi('addi', 5, 5, 10); g.opi('addi', 5, 5, 100); g.op('add', 6, 5, 5); g.chk(6)   # youngest producer wins
g.t(); g.li(5, 3); g.li(6, 4); g.op('add', 7, 5, 6); g.chk(7)                    # rs1 from MEM/WB, rs2 from EX/MEM
g.t(); g.li(5, 3); g.li(6, 4); g.op('sub', 7, 6, 5); g.chk(7)                    # swapped roles
g.t(); g.li(5, 8); g.li(5, 9); g.li(5, 10); g.op('add', 7, 5, 5); g.chk(7)       # three writers same reg
addg("pipe_fwd_priority", g, stl=True, red=True)

g = G(); g.t(); g.li(5, 0); g.li(6, 1)
for _ in range(14): g.op('add', 7, 5, 6); g.op('add', 5, 6, 7); g.op('add', 6, 7, 5)    # Fibonacci-style
for r in (5, 6, 7): g.chk(r)
addg("pipe_multi_dep_fib", g, stl=True, red=True)

for seed in (11, 12, 13):
    rg = random.Random(seed); g = G(); g.t(); pool = [5, 6, 7, 28, 29]
    for r in pool: g.li(r, rg.getrandbits(32))
