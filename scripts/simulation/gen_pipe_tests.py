g.chk(5); g.chk(6); g.chk(7)
addg("pipe_fwd_exex_chain", g, stl=True, red=True)

g = G(); g.t(); g.li(5, 7); g.op('add', 6, 5, 0); g.chk(6)    # EX/MEM -> rs1, dist 1
