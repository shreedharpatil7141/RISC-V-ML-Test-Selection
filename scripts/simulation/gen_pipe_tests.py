#!/usr/bin/env python3
"""Generate Stage-2 pipeline directed tests -> tests/directed/pipeline/*.s, manifest.csv, expected_perf.csv.
Self-checking convention as Stage 1: gp(x3)=test number >=2 before each check; pass => gp=1; ECALL.
Expected register/memory values come from the small emulator inside class G (independent of RTL and ISS).
expected_perf.csv holds stall/redirect counts known BY CONSTRUCTION for selected tests (-1 = not asserted);
the checker also compares RTL stats against a model computed from the ISS trace.
Random-stress tests (pipe_rand_*) are checked by trace equivalence (RTL pipe == RTL single == ISS), not by values."""
import os, random
M = 0xFFFFFFFF
def s32(x): x &= M; return x - (1 << 32) if x >> 31 else x
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'tests', 'directed', 'pipeline')
BASE = 0x5000
RR = {'add': lambda a,b:(a+b)&M, 'sub': lambda a,b:(a-b)&M, 'sll': lambda a,b:(a<<(b&31))&M,
      'slt': lambda a,b:int(s32(a)<s32(b)), 'sltu': lambda a,b:int(a<b), 'xor': lambda a,b:a^b,
      'srl': lambda a,b:a>>(b&31), 'sra': lambda a,b:(s32(a)>>(b&31))&M, 'or': lambda a,b:a|b, 'and': lambda a,b:a&b}
RI = {'addi': lambda a,i:(a+i)&M, 'slti': lambda a,i:int(s32(a)<i), 'sltiu': lambda a,i:int(a<(i&M)),
      'xori': lambda a,i:(a^i)&M, 'ori': lambda a,i:(a|i)&M, 'andi': lambda a,i:(a&i)&M}
BR = {'beq': lambda a,b:a==b, 'bne': lambda a,b:a!=b, 'blt': lambda a,b:s32(a)<s32(b),
      'bge': lambda a,b:s32(a)>=s32(b), 'bltu': lambda a,b:a<b, 'bgeu': lambda a,b:a>=b}

class G:
    """Program builder + tiny architectural emulator (straight-line only; control flow handled by caller)."""
    def __init__(s):
        s.l = []; s.r = [0]*32; s.mem = bytearray(0x10000); s.n = 1; s.u = 0; s.stl = 0; s.red = 0
    def raw(s, *x): s.l += list(x)
    def t(s): s.n += 1; s.l.append(f"li gp, {s.n}")
    def set(s, rd, v):
        if rd: s.r[rd] = v & M
    def li(s, rd, v): s.l.append(f"li x{rd}, {v}"); s.set(rd, v)
    def op(s, m, rd, a, b): s.l.append(f"{m} x{rd}, x{a}, x{b}"); s.set(rd, RR[m](s.r[a], s.r[b]))
    def opi(s, m, rd, a, i): s.l.append(f"{m} x{rd}, x{a}, {i}"); s.set(rd, RI[m](s.r[a], i))
    def nop(s): s.l.append("nop")
    def store(s, m, src, base, off):
        n = {'sb':1,'sh':2,'sw':4}[m]; ad = (s.r[base] + off) & M
        s.l.append(f"{m} x{src}, {off}(x{base})"); s.mem[ad:ad+n] = (s.r[src] & ((1 << 8*n) - 1)).to_bytes(n, 'little')
    def load(s, m, rd, base, off):
        n = {'lb':1,'lh':2,'lw':4,'lbu':1,'lhu':2}[m]; ad = (s.r[base] + off) & M
        s.l.append(f"{m} x{rd}, {off}(x{base})")
        v = int.from_bytes(s.mem[ad:ad+n], 'little')
        if m in ('lb','lh'): v = ((v ^ (1 << (8*n-1))) - (1 << (8*n-1))) & M
        s.set(rd, v)
    def chk(s, r, tmp=31):     # compare x{r} with emulator value (taken beq -> 1 redirect)
        s.u += 1; s.l += [f"li x{tmp}, {s.r[r]}", f"beq x{r}, x{tmp}, ok{s.u}", "j fail", f"ok{s.u}:"]; s.red += 1
    def chkv(s, r, v, tmp=31):
        s.u += 1; s.l += [f"li x{tmp}, {v}", f"beq x{r}, x{tmp}, ok{s.u}", "j fail", f"ok{s.u}:"]; s.red += 1
    def lbl(s): s.u += 1; return s.u
    def text(s, name):
        return f"# {name} (generated by gen_pipe_tests.py - do not edit)\n" + "\n".join(s.l) + "\nli gp, 1\necall\nfail:\necall\n"

tests = {}   # name -> (src, cause, check_gp, exp_stalls, exp_redirects)
def add(name, src, cause=1, gp=1, stl=-1, red=-1): tests[name] = (src, cause, gp, stl, red)
def addg(name, g, stl=False, red=False):
    # constructed redirect count: chk beq's (+ explicit g.red) ; final 'ecall' has none. Only asserted when asked.
    add(name, g.text(name), 1, 1, g.stl if stl else -1, g.red if red else -1)
def prep(g):   # base pointer + seeded data words
    g.li(8, BASE)

# ---------------- basic / dependency / forwarding ----------------
g = G(); g.t(); g.li(5, 10); g.li(6, 20); g.op('add', 7, 5, 6); g.opi('addi', 28, 5, 3); g.op('sub', 29, 6, 5); g.op('xor', 30, 5, 6)
for r in (7, 28, 29, 30): g.chk(r)
addg("pipe_basic_independent", g, stl=True, red=True)

g = G(); g.t(); g.li(5, 1)
