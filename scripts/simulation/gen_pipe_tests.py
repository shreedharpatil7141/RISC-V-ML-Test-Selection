# ---------------- constrained-random hazard stress (trace-equivalence checked) ----------------
def rand_prog(seed, ninst):
    rg = random.Random(seed); out = []; cnt = [0]
    pool = [5, 6, 7, 9, 10, 11, 12, 13, 28, 29]; srcp = pool + [0, 0]; dstp = pool * 4 + [0]
    def lab(): cnt[0] += 1; return f"r{cnt[0]}"
    def simple():
        k = rg.random(); rd = rg.choice(dstp)
        if k < 0.30: return f"{rg.choice(list(RR))} x{rd}, x{rg.choice(srcp)}, x{rg.choice(srcp)}"
        if k < 0.50: return f"{rg.choice(list(RI))} x{rd}, x{rg.choice(srcp)}, {rg.randrange(-2048, 2048)}"
        if k < 0.58: return f"{rg.choice(['slli','srli','srai'])} x{rd}, x{rg.choice(srcp)}, {rg.randrange(32)}"
        if k < 0.64: return f"lui x{rd}, {rg.randrange(1 << 20)}"
        if k < 0.84:
            m = rg.choice(['lb','lbu','lh','lhu','lw','lw','lw']); n = {'lb':1,'lbu':1,'lh':2,'lhu':2,'lw':4}[m]
            return f"{m} x{rd}, {rg.randrange(-16, 16) * 4 // n * n}(x8)"
        m = rg.choice(['sb','sh','sw','sw']); n = {'sb':1,'sh':2,'sw':4}[m]
        return f"{m} x{rg.choice(srcp)}, {rg.randrange(-16, 16) * 4 // n * n}(x8)"
    out += [f"li x8, {BASE}"] + [f"li x{r}, {rg.getrandbits(32)}" for r in pool]
    for i in range(16): out.append(f"sw x{rg.choice(pool)}, {4*i - 32}(x8)")
    made = 0
    while made < ninst:
        k = rg.random()
        if k < 0.55: out.append(simple()); made += 1
        elif k < 0.75:                                           # forward branch skipping 1-3 insns
            L = lab(); out.append(f"{rg.choice(list(BR))} x{rg.choice(srcp)}, x{rg.choice(srcp)}, {L}")
            for _ in range(rg.randrange(1, 4)): out.append(simple())
            out.append(f"{L}:"); made += 4
        elif k < 0.83:                                           # forward jal skipping 1-2
            L = lab(); out.append(f"jal x{rg.choice([0, 1])}, {L}")
            for _ in range(rg.randrange(1, 3)): out.append(simple())
            out.append(f"{L}:"); made += 3
        elif k < 0.89:                                           # forward jalr via la (address built right before)
            L = lab(); out += [f"la x16, {L}", f"jalr x{rg.choice([0, 1])}, 0(x16)"]
            for _ in range(rg.randrange(1, 3)): out.append(simple())
            out.append(f"{L}:"); made += 5
        else:                                                    # small counted loop (backward branch)
            L = lab(); out += ["li x17, 3", f"{L}:"]
            for _ in range(rg.randrange(2, 5)): out.append(simple())
            out += ["addi x17, x17, -1", f"bnez x17, {L}"]; made += 8
    out += ["li gp, 1", "ecall", "fail:", "ecall"]
    return f"# constrained-random pipeline stress seed={seed} (generated)\n" + "\n".join(out) + "\n"
