#!/usr/bin/env python3
"""Generate Stage-3 RV32M directed tests -> tests/directed/m_extension/*.s + manifest.csv.
Self-checking convention as Stage 1/2: gp(x3)=test number >=2 before each check; pass => gp=1 then ECALL.
Expected values come from m_model.md_ref (shift-add multiply / restoring division) - a formulation independent
of the ISS (rv32i_iss.md_exec) and of the RTL. Operands are loaded with `li`, results compared with beq/j fail."""
import os, random, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from m_model import md_ref, OPS
M32 = 0xFFFFFFFF
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'tests', 'directed', 'm_extension')
BASE = 0x5000
def n(x): return x & M32
OPND = [0, 1, M32, 2, n(-2), 3, n(-3), 7, n(-7), 0xFFFF, 0x10000, 0x7FFFFFFF, 0x80000000, 0x80000001, 0x12345678, 0xA5A5A5A5]
def s32(x): x &= M32; return x - (1 << 32) if x >> 31 else x

class P:
    def __init__(s): s.l = []; s.n = 1; s.u = 0
    def raw(s, *x): s.l += list(x)
    def t(s): s.n += 1; s.l.append(f"li gp, {s.n}")
    def chk(s, a, b): s.u += 1; s.l += [f"beq {a}, {b}, ok{s.u}", "j fail", f"ok{s.u}:"]
    def lbl(s): s.u += 1; return s.u
    def text(s, name): return f"# {name} (generated by gen_m_tests.py - do not edit)\n" + "\n".join(s.l) + "\nli gp, 1\necall\nfail:\necall\n"

tests = {}
def add(name, p): tests[name] = p.text(name)

def vec(p, op, a, b):          # one self-checked vector: t2 = op(t0, t1)
    p.t(); p.raw(f"li t0, {a}", f"li t1, {b}", f"{op} t2, t0, t1", f"li t3, {md_ref(op, a, b)}"); p.chk('t2', 't3')

def alias(p, op, a, b):        # rd==rs1, rd==rs2, rs1==rs2
    p.t(); p.raw(f"li t0, {a}", f"li t1, {b}", f"{op} t0, t0, t1", f"li t3, {md_ref(op, a, b)}"); p.chk('t0', 't3')
    p.t(); p.raw(f"li t0, {a}", f"li t1, {b}", f"{op} t1, t0, t1", f"li t3, {md_ref(op, a, b)}"); p.chk('t1', 't3')
    p.t(); p.raw(f"li t0, {a}", f"{op} t0, t0, t0", f"li t3, {md_ref(op, a, a)}"); p.chk('t0', 't3')
    p.t(); p.raw(f"li t0, {a}", f"{op} t2, t0, t0", f"li t3, {md_ref(op, a, a)}"); p.chk('t2', 't3')

for k, op in enumerate(OPS):
    p = P()
    for a in OPND:
        for b in OPND: vec(p, op, a, b)
    for a, b in [(0x80000000, M32), (0x12345678, 7), (n(-7), 2), (5, 0), (0, 0), (M32, M32)]: alias(p, op, a, b)
    add(f"m_{op}", p)
    rg = random.Random(0x3000 + k); p = P()
    for _ in range(150):
        pick = lambda: rg.choice(OPND) if rg.random() < 0.35 else (rg.getrandbits(32) if rg.random() < 0.7 else rg.getrandbits(rg.randrange(1, 17)))
        vec(p, op, pick(), pick())
    add(f"m_rand_{op}", p)

# division by zero (divisor in a register holding 0, and the x0 register itself)
p = P()
for op in ('div', 'divu', 'rem', 'remu'):
    for a in [0, 1, M32, 0x80000000, 0x7FFFFFFF, 0x12345678, 0xDEADBEEF]:
        vec(p, op, a, 0)
        p.t(); p.raw(f"li t0, {a}", f"{op} t2, t0, x0", f"li t3, {md_ref(op, a, 0)}"); p.chk('t2', 't3')
add("m_divzero", p)

# signed overflow and neighbours
p = P()
for op in ('div', 'divu', 'rem', 'remu'):
    for a, b in [(0x80000000, M32), (0x80000000, 0x80000000), (M32, 0x80000000), (M32, M32), (0x80000000, 1), (0x80000001, M32), (0x7FFFFFFF, M32), (0x80000000, 2)]:
        vec(p, op, a, b)
add("m_overflow", p)

# sign matrix: +-7 / +-2, +-3 and +-6 for all signed/unsigned div/rem/mulh*
p = P()
for a in (7, n(-7), 6, n(-6)):
    for b in (2, n(-2), 3, n(-3), 6, n(-6)):
        for op in OPS: vec(p, op, a, b)
add("m_sign_matrix", p)

# x0 as destination / source
p = P()
p.t(); p.raw("li t0, 5", "li t1, 3")
for op in OPS: p.raw(f"{op} x0, t0, t1")
p.raw("add t2, x0, x0"); p.chk('t2', 'x0')                     # x0 still zero
p.raw("li t3, 5"); p.chk('t0', 't3'); p.raw("li t3, 3"); p.chk('t1', 't3')
for op in OPS:
    p.t(); p.raw("li t1, 77", f"{op} t2, x0, t1", f"li t3, {md_ref(op, 0, 77)}"); p.chk('t2', 't3')       # rs1 = x0
    p.t(); p.raw("li t0, 77", f"{op} t2, t0, x0", f"li t3, {md_ref(op, 77, 0)}"); p.chk('t2', 't3')       # rs2 = x0
    p.t(); p.raw(f"{op} t2, x0, x0", f"li t3, {md_ref(op, 0, 0)}"); p.chk('t2', 't3')                      # both x0
add("m_x0", p)

# dependent chain through all ops (software-visible forwarding-free check of sequencing)
p = P(); regs = {5: 0x12345678, 6: 7, 7: 0, 28: 0}
p.t(); p.raw(f"li t0, {regs[5]}", f"li t1, {regs[6]}")
names = {5: 't0', 6: 't1', 7: 't2', 28: 't3'}
seq = [('mul', 7, 5, 6), ('div', 28, 7, 6), ('rem', 5, 7, 6), ('mulh', 6, 28, 28), ('mulhu', 7, 28, 6), ('divu', 28, 7, 28),
       ('mulhsu', 5, 28, 7), ('remu', 6, 7, 5), ('mul', 7, 6, 5), ('div', 28, 5, 7), ('rem', 6, 28, 5), ('mulh', 5, 6, 7)]
for _ in range(3):
    for op, d, a, b in seq:
        p.raw(f"{op} {names[d]}, {names[a]}, {names[b]}"); regs[d] = md_ref(op, regs[a], regs[b])
for r in (5, 6, 7, 28): p.raw(f"li t4, {regs[r]}"); p.chk(names[r], 't4')
add("m_chain", p)

# M results used as store data, branch operands, JALR base
p = P(); p.raw(f"li s0, {BASE}")
for op in OPS:
    a, b = 0x1E241, 0x181CD
    p.t(); p.raw(f"li t0, {a}", f"li t1, {b}", f"{op} t2, t0, t1", "sw t2, 0(s0)", "lw t3, 0(s0)", f"li t4, {md_ref(op, a, b)}"); p.chk('t3', 't4')
for br, f in (('blt', lambda x, y: s32(x) < s32(y)), ('bge', lambda x, y: s32(x) >= s32(y)), ('bltu', lambda x, y: x < y), ('bgeu', lambda x, y: x >= y),
              ('beq', lambda x, y: x == y), ('bne', lambda x, y: x != y)):
    for a, b in [(100, 7), (n(-100), 7), (7, 7), (0, 5)]:
        q, r = md_ref('divu', a, b), md_ref('remu', a, b); k = p.lbl()
        p.t(); p.raw(f"li t0, {a}", f"li t1, {b}", "divu t2, t0, t1", "remu t3, t0, t1")
        if f(q, r): p.raw(f"{br} t2, t3, bt{k}", "j fail", f"bt{k}:")
        else:       p.raw(f"{br} t2, t3, bf{k}", f"j bc{k}", f"bf{k}:", "j fail", f"bc{k}:")
p.t(); p.raw("la t0, Lj", "li t1, 1", "mul t2, t0, t1", "jalr x0, 0(t2)", "j fail", "Lj:")      # JALR base from MUL
p.t(); p.raw("la t0, Lk", "li t1, 3", "mul t2, t0, t1", "divu t2, t2, t1", "jalr x0, 0(t2)", "j fail", "Lk:")   # MUL then DIVU
add("m_misc_use", p)

if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith(('.s', '.csv')): os.remove(os.path.join(OUT, f))
    with open(os.path.join(OUT, 'manifest.csv'), 'w', newline='\n') as m:
        m.write("name,expect_cause,check_gp\n")
        for name, src in sorted(tests.items()):
            open(os.path.join(OUT, name + '.s'), 'w', newline='\n').write(src); m.write(f"{name},1,1\n")
    print(f"generated {len(tests)} M-extension tests -> {os.path.normpath(OUT)}")
